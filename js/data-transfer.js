/** @returns {string[]} every object store in the shop database right now. */
export async function enumerateStoreNames() {
  const db = await openDB();
  if (FORBIDDEN_DATABASES.includes(db.name)) {
    throw new Error('قاعدة بيانات خاطئة');
  }
  return Array.from(db.objectStoreNames);
}

function readAll(db, name) {
  return new Promise((resolve, reject) => {
    let req;
    try {
      req = db.transaction(name, 'readonly').objectStore(name).getAll();
    } catch (err) {
      reject(err);
      return;
    }
    req.onsuccess = () => resolve(req.result || []);
    req.onerror = () => reject(req.error);
  });
}

function storageBackend() {
  try {
    if (typeof localStorage !== 'undefined' && localStorage) return localStorage;
  } catch {
    /* blocked store → nothing to back up */
  }
  return null;
}

/** True when `key` belongs to the app itself rather than to the shop's data. */
export function isReservedStorageKey(key) {
  return RESERVED_STORAGE_PREFIXES.some((p) => String(key).startsWith(p));
}

/**
 * Every localStorage entry that is shop data — the reserved app keys are
 * stripped out, so a backup can never carry the interim activation.
 *
 * @returns {Promise<Record<string,string>>}
 */
export async function readStoreStorage() {
  const s = storageBackend();
  const out = {};
  if (!s) return out;
  let keys = [];
  try {
    keys = Object.keys(s);
  } catch {
    return out;
  }
  for (const k of keys) {
    if (isReservedStorageKey(k)) continue;
    try {
      out[k] = s.getItem(k);
    } catch {
      /* unreadable key — skip rather than fail the whole export */
    }
  }
  return out;
}

/* ------------------------------------------------------------------ *
 * Checksums
 * ------------------------------------------------------------------ */

/**
 * The financial cross-check a human reads and a restore re-computes. Every
 * figure here is derived from the records, so if a restore round-trips a table
 * incompletely these numbers cannot come back equal.
 *
 * @param {Record<string, any[]>} stores
 */
export function computeTotals(stores) {
  const products = stores[STORES.products] || [];
  const sales = stores[STORES.sales] || [];
  const purchases = stores[STORES.purchases] || [];
  const invoices = stores[STORES.supplierInvoices] || [];
  const payments = stores[STORES.supplierPayments] || [];

  const totalSales = sumBy(sales, (s) => s.total);
  const totalPurchases = sumBy(purchases, (p) => p.total);
  const totalSupplierInvoices = sumBy(invoices, (i) => i.total);
  // A supplier payment stores its figure as `amount`, not `total` (see
  // `db.createSupplierPayment`). Reading the wrong field here would make the
  // checksum say every shop owes its suppliers everything it ever paid them.
  const totalSupplierPayments = sumBy(payments, (p) => (p.amount ?? p.total));

  let recordCount = 0;
  for (const list of Object.values(stores)) if (Array.isArray(list)) recordCount += list.length;

  return {
    recordCount,
    productCount: products.length,
    unitsInStock: products.reduce((t, p) => t + stockOf(p), 0),
    inventoryValue: round2(inventoryValue(products)),
    salesCount: sales.length,
    totalSales: round2(totalSales),
    purchaseCount: purchases.length,
    totalPurchases: round2(totalPurchases),
    supplierInvoiceCount: invoices.length,
    totalSupplierInvoices: round2(totalSupplierInvoices),
    supplierPaymentCount: payments.length,
    totalSupplierPayments: round2(totalSupplierPayments),
    supplierDebt: round2(totalSupplierInvoices - totalSupplierPayments),
  };
}

/**
 * The counters that decide the NEXT receipt number and stop two devices
 * handing out the same invoice number after a restore.
 *
 * `checkout.js` derives the next number from "how many sales already carry
 * today's local day", so importing the sales themselves already restores the
 * numbering. These are exported anyway for two reasons: the number is verified
 * after a restore like every other checksum, and if a build ever introduces a
 * real stored counter, it lands in a table this module enumerates automatically
 * and is covered without anyone remembering to edit a list.
 *
 * @param {Record<string, any[]>} stores
 */
export function computeCounters(stores) {
  const saleCountByLocalDay = {};
  for (const s of stores[STORES.sales] || []) {
    const key = dayKeyOf(s.timestamp);
    saleCountByLocalDay[key] = (saleCountByLocalDay[key] || 0) + 1;
  }
  return { saleCountByLocalDay, nextReceiptSeqByLocalDay: { ...saleCountByLocalDay } };
}

/**
 * The exact bytes the fingerprint covers. Built as a fixed-shape object so that
 * building it from live records and building it from a parsed file produce the
 * same key order, and therefore the same string, and therefore the same hash.
 */
function canonicalPayload(p) {
  return JSON.stringify({ stores: p.stores, storage: p.storage, counters: p.counters });
}

/**
 * Reads every store in IndexedDB plus localStorage and builds the file.
 *
 * Nothing here filters: whatever the schema has on the day this runs is what
 * ships. A table added next month is exported by this code without being added
 * to it.
 *
 * @param {{appVersion?:string}} [opts]
 * @returns {Promise<object>} the file, ready to be stringified
 */
export async function buildBackupFile(opts = {}) {
  const db = await openDB();
  const names = Array.from(db.objectStoreNames);

  /** @type {Record<string, any[]>} */
  const stores = {};
  for (const name of names) {
    const rows = await readAll(db, name);
    const out = [];
    for (const r of rows) out.push(await toSerializable(r));
    stores[name] = out;
  }

  const storage = { localStorage: await readStoreStorage() };
  const counters = computeCounters(stores);
  const totals = computeTotals(stores);

  const fingerprint = {
    algo: 'SHA-256',
    value: await sha256Hex(canonicalPayload({ stores, storage, counters })),
  };

  return {
    formatVersion: FORMAT_VERSION,
    kind: FORMAT_KIND,
    app: LEGACY_APP_MARK,
    appVersion: String(opts.appVersion || DB_VERSION),
    schemaVersion: DB_VERSION,
    database: DB_NAME,
    exportedAt: new Date().toISOString(),
    stores,
    storage,
    counters,
    totals,
    fingerprint,
    // `activation` is intentionally absent and must stay absent: the interim
    // gate's state is not shop data and must never be able to lock a device
    // that restores this file.
    activation: null,
  };
}

/**
 * Recomputes the fingerprint of a parsed file and compares it with the one it
 * claims. A file edited by hand — or truncated and stitched back together —
 * changes its payload, and this is where that is caught.
 *
 * @param {object} file
 * @returns {Promise<{ok:boolean, reason:'ok'|'missing'|'mismatch', expected:string|null, actual:string}>}
 */
export async function verifyFingerprint(file) {
  const expected = file?.fingerprint?.value || null;
  if (!expected) return { ok: false, reason: 'missing', expected: null, actual: '' };
  const actual = await sha256Hex(canonicalPayload({
    stores: file.stores, storage: file.storage, counters: file.counters,
  }));
  return { ok: actual === expected, reason: actual === expected ? 'ok' : 'mismatch', expected, actual };
}

/* ------------------------------------------------------------------ *
 * Validation
 * ------------------------------------------------------------------ */

const err = (message) => ({ ok: false, error: message });

/**
 * Decides whether a raw file may be allowed near the live database, and in
 * which version it is written. Never opens a transaction, never writes.
 *
 * @param {string|object} raw  the file's text, or an already-parsed object
 * @returns {Promise<{ok:boolean, error?:string, file?:object, formatVersion?:number}>}
 */
export async function validateBackupFile(raw) {
  let parsed = raw;
  if (typeof raw === 'string') {
    try {
      parsed = JSON.parse(raw);
    } catch {
      return err('الملف ليس ملف JSON صالحاً');
    }
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    return err('ملف النسخة الاحتياطية غير صالح');
  }

  // A Google Drive backup is a different file family with its own validator and
  // its own screen. Refusing it here is honest; silently importing it through a
  // second code path is how two restore paths drift apart.
  if (parsed.sections || parsed.kind === 'storehub-drive-backup') {
    return err('هذا ملف نسخ Google Drive — استخدم زر الاستعادة من Google Drive');
  }

  let version;
  if (Number.isFinite(parsed.formatVersion)) version = parsed.formatVersion;
  else if (parsed.app === LEGACY_APP_MARK) version = 1;
  else return err('هذا الملف ليس نسخة احتياطية من Store Hub');

  if (!Number.isInteger(version) || version < 1) return err('ملف النسخة الاحتياطية غير صالح');

  if (version > FORMAT_VERSION) {
    return err(
      `الملف من إصدار أحدث (${version}) من هذا التطبيق (${FORMAT_VERSION}). حدّث التطبيق أولاً ثم أعد الاستيراد.`,
    );
  }
  if (!SUPPORTED_FORMAT_VERSIONS.includes(version)) {
    return err(`إصدار صيغة النسخة (${version}) غير مدعوم في هذا التطبيق.`);
  }

  if (version === 1) {
    if (parsed.app !== LEGACY_APP_MARK) return err('هذا الملف ليس نسخة احتياطية من Store Hub');
    if (!Array.isArray(parsed.products)) return err('النسخة الاحتياطية لا تحتوي على قائمة المنتجات');
    if (!Array.isArray(parsed.sales)) return err('النسخة الاحتياطية لا تحتوي على قائمة الفواتير');
    if (parsed.settings !== undefined && typeof parsed.settings !== 'object') {
      return err('بيانات المتجر داخل الملف غير صالحة');
    }
    return { ok: true, file: parsed, formatVersion: 1 };
  }

  // version 2
  if (parsed.kind !== FORMAT_KIND) return err('ملف النسخة الاحتياطية غير صالح');
  if (!parsed.stores || typeof parsed.stores !== 'object' || Array.isArray(parsed.stores)) {
    return err('الملف لا يحتوي على الجداول');
  }
  for (const [name, list] of Object.entries(parsed.stores)) {
    if (!Array.isArray(list)) return err(`جدول "${name}" داخل الملف غير صالح`);
  }
  if (!parsed.fingerprint || typeof parsed.fingerprint.value !== 'string') {
    return err('الملف لا يحمل بصمة تحقق — مرفوض');
  }
  const fp = await verifyFingerprint(parsed);
  if (!fp.ok) {
    return err(fp.reason === 'missing' ? 'بصمة الملف مفقودة' : 'بصمة الملف لا تتطابق مع محتواه — ربما عُدّل الملف');
  }
  return { ok: true, file: parsed, formatVersion: 2 };
}

/* ------------------------------------------------------------------ *
 * Normalising a validated file into "records to put, stores to clear"
 * ------------------------------------------------------------------ */

/**
 * Translates any supported version into the current shape: which object stores
 * to write, with which records, and whether every store may be cleared first.
 *
 * @param {object} file     a validated file
 * @param {number} version
 * @param {string[]} target the object store names this build actually has
 */
export function planRestore(file, version, target) {
  if (version === 1) {
    /** @type {Record<string, any[]>} */
    const stores = {};
    const pick = (name, value) => {
      if (value === undefined || value === null) return;
      stores[name] = Array.isArray(value) ? value : [value];
    };
    for (const name of target) pick(name, file[name]);
    // `settings` is a single record in the legacy shape.
    if (file.settings && !Array.isArray(file.settings)) stores[STORES.settings] = [file.settings];
    return { stores, complete: false, storage: null };
  }

  const stores = {};
  for (const [name, list] of Object.entries(file.stores)) stores[name] = list;
  const storage = file.storage?.localStorage ?? null;
  return { stores, complete: true, storage };
}

/* ------------------------------------------------------------------ *
 * The atomic write
 * ------------------------------------------------------------------ */

function atomicReplace(db, plan) {
  const names = Array.from(db.objectStoreNames);

  // A store the file names that this build does not have means the file came
  // from a build with tables we know nothing about. Refusing is the only safe
  // answer — proceeding would drop that table on the floor silently.
  const unknown = Object.keys(plan.stores).filter((n) => !names.includes(n));
  if (unknown.length) {
    throw new Error(`الملف يحوي جدولاً غير موجود في هذا التطبيق: ${unknown.join('، ')}`);
  }

  return new Promise((resolve, reject) => {
    let tx;
    try {
      tx = db.transaction(names, 'readwrite');
    } catch (e) {
      reject(e);
      return;
    }
    let settled = false;
    const fail = (e) => {
      if (settled) return;
      settled = true;
      reject(e);
    };
    tx.oncomplete = () => {
      if (settled) return;
      settled = true;
      resolve();
    };
    tx.onerror = () => fail(tx.error || new Error('فشلت معالجة الاستيراد'));
    tx.onabort = () => fail(tx.error || new Error('أُلغيت معالجة الاستيراد'));

    try {
      for (const name of names) {
        // A complete (v2) restore clears every table, including ones the file
        // knows as empty. A legacy restore only clears what the file carries,
        // so an old file cannot wipe a ledger the owner entered by hand.
        if (plan.complete || Object.prototype.hasOwnProperty.call(plan.stores, name)) {
          tx.objectStore(name).clear();
        }
      }
      for (const [name, list] of Object.entries(plan.stores)) {
        const os = tx.objectStore(name);
        for (const record of list) os.put(record);
      }
    } catch (e) {
      try { tx.abort(); } catch { /* already dead */ }
      fail(e);
    }
  });
}

/* ------------------------------------------------------------------ *
 * Reading the database back, for verification
 * ------------------------------------------------------------------ */

/** @returns {Promise<Record<string, any[]>>} every store, as stored. */
export async function readAllStores() {
  const db = await openDB();
  const out = {};
  for (const name of Array.from(db.objectStoreNames)) out[name] = await readAll(db, name);
  return out;
}

/**
 * Canonical, order-independent text of a store: records sorted by their JSON so
 * two reads of the same rows compare equal no matter what order IndexedDB
 * handed them back in.
 */
function canonicalStores(stores) {
  const out = {};
  for (const name of Object.keys(stores).sort()) {
    const rows = Array.isArray(stores[name]) ? stores[name] : [];
    out[name] = rows.map((r) => JSON.stringify(r ?? null)).sort();
  }
  return JSON.stringify(out);
}

/**
 * Recomputes counts, checksums and counters from the live database and reports
 * every difference against what the file promised.
 *
 * @param {object} plan      from `planRestore`
 * @param {object} file      the file that was imported
 * @returns {Promise<string[]>} human-readable differences; empty means identical
 */
export async function compareToPlan(plan, file) {
  const mismatches = [];
  const live = await readAllStores();

  /** What the database is expected to hold once the restore has landed. */
  const expectedStores = {};
  for (const name of Object.keys(live).sort()) {
    const written = plan.complete || Object.prototype.hasOwnProperty.call(plan.stores, name);
    expectedStores[name] = written ? (plan.stores[name] || []) : live[name];
  }
  for (const name of Object.keys(plan.stores)) {
    if (!(name in live)) mismatches.push(`${name}: مفقود بعد الاستيراد`);
  }

  for (const name of Object.keys(expectedStores).sort()) {
    if (live[name].length !== expectedStores[name].length) {
      mismatches.push(`${name}: ${expectedStores[name].length} مقابل ${live[name].length}`);
    }
  }

  // Structural equality, not just counts: a restore that brought back the right
  // number of rows with one price changed is still a broken restore.
  if (canonicalStores(live) !== canonicalStores(expectedStores)) {
    mismatches.push('محتوى أحد الجداول غير مطابق بعد الاستيراد');
  }

  // Checksums are re-derived from the rows that are expected to be present, so
  // a legacy file that legitimately says nothing about a newer table cannot be
  // blamed for that table's untouched contents.
  const derived = computeTotals(expectedStores);
  const wanted = file.totals || derived;
  const liveTotals = computeTotals(live);
  for (const k of Object.keys(wanted)) {
    if (k === 'recordCount') continue;
    if (!(k in liveTotals)) continue;
    if (liveTotals[k] !== wanted[k]) mismatches.push(`${k}: ${wanted[k]} مقابل ${liveTotals[k]}`);
  }
  // And the file's own arithmetic has to be right: `totals` is derived data and
  // is not covered by the fingerprint, so this is the only place a hand-edited
  // summary number gets caught.
  if (file.totals) {
    for (const k of Object.keys(derived)) {
      if (k === 'recordCount') continue;
      if (file.totals[k] !== undefined && file.totals[k] !== derived[k]) {
        mismatches.push(`${k} في الملف غير صحيح`);
      }
    }
  }

  const wantedCounters = file.counters || computeCounters(expectedStores);
  const liveCounters = computeCounters(live);
  if (
    wantedCounters.saleCountByLocalDay &&
    JSON.stringify(liveCounters.saleCountByLocalDay) !== JSON.stringify(wantedCounters.saleCountByLocalDay)
  ) {
    mismatches.push('عدّاد الفواتير اليومي غير مطابق');
  }

  return mismatches;
}

/* ------------------------------------------------------------------ *
 * The safety snapshot (undo)
 * ------------------------------------------------------------------ */

export const SNAPSHOT_DB = 'saher_backup_safety';
export const SNAPSHOT_DB_VERSION = 1;
export const SNAPSHOT_STORE = 'snapshots';
const SNAPSHOT_AUTO_ID = 'auto';

function openSnapshotDB() {
  return new Promise((resolve, reject) => {
    const req = indexedDB.open(SNAPSHOT_DB, SNAPSHOT_DB_VERSION);
    req.onupgradeneeded = () => {
      const db = req.result;
      if (!db.objectStoreNames.contains(SNAPSHOT_STORE)) {
        db.createObjectStore(SNAPSHOT_STORE, { keyPath: 'id' });
      }
    };
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

/**
 * Keeps an automatic copy of whatever the device held immediately before a
 * restore, in its OWN database — so it cannot be mistaken for shop data, is
 * never exported as a table, and survives a restore that wipes `saher_db`.
 *
 * @param {object} file  a file produced by `buildBackupFile`
 * @param {{id?:string}} [opts]
 */
export async function saveSafetySnapshot(file, opts = {}) {
  const db = await openSnapshotDB();
  try {
    await new Promise((resolve, reject) => {
      const tx = db.transaction(SNAPSHOT_STORE, 'readwrite');
      tx.oncomplete = resolve;
      tx.onerror = () => reject(tx.error);
      tx.onabort = () => reject(tx.error);
      tx.objectStore(SNAPSHOT_STORE).put({
        id: opts.id || SNAPSHOT_AUTO_ID,
        savedAt: new Date().toISOString(),
        file,
      });
    });
  } finally {
    db.close();
  }
  lastSnapshot = file; // in-memory copy: the fastest rollback of all
  return file;
}

/** @type {object|null} */
let lastSnapshot = null;

/** @returns {Promise<object|null>} the most recent safety snapshot, if any. */
export async function readSafetySnapshot(opts = {}) {
  if (opts.id === undefined && lastSnapshot) return lastSnapshot;
  const db = await openSnapshotDB();
  try {
    return await new Promise((resolve, reject) => {
      const tx = db.transaction(SNAPSHOT_STORE, 'readonly');
      const req = tx.objectStore(SNAPSHOT_STORE).get(opts.id || SNAPSHOT_AUTO_ID);
      req.onsuccess = () => resolve(req.result?.file ?? null);
      req.onerror = () => reject(req.error);
    });
  } finally {
    db.close();
  }
}

/** Test seam: forget the in-memory copy so a test can read from the database. */
export function _resetSafetySnapshotCache() {
  lastSnapshot = null;
}

/* ------------------------------------------------------------------ *
 * Export bookkeeping (drives the "you have not backed up lately" reminder)
 * ------------------------------------------------------------------ */

export const LAST_EXPORT_KEY = 'saher.backup.lastExportAt';
export const BACKUP_REMINDER_DAYS = 3;

/** Remembers when a file backup last succeeded. */
export function markExportedAt(now = new Date()) {
  try {
    const s = storageBackend();
    if (s) s.setItem(LAST_EXPORT_KEY, now.toISOString());
  } catch {
    /* a missing reminder is not worth an error */
  }
}

/** @returns {Date|null} when the last successful file export happened, if known. */
export function lastExportAt() {
  try {
    const s = storageBackend();
    const v = s?.getItem(LAST_EXPORT_KEY);
    return v ? new Date(v) : null;
  } catch {
    return null;
  }
}

/** Has it been long enough that the owner should be nudged again? */
export function isBackupDue(now = new Date()) {
  const last = lastExportAt();
  if (!last || Number.isNaN(last.getTime())) return true;
  return now.getTime() - last.getTime() >= BACKUP_REMINDER_DAYS * 86400000;
}

/* ------------------------------------------------------------------ *
 * Restore
 * ------------------------------------------------------------------ */

/**
 * Restores a validated file: snapshot → write → re-read → verify → or undo.
 *
 * The write itself is ONE IndexedDB transaction over every store, so a failure
 * part-way through rolls the whole thing back and the device is left as it was.
 * The snapshot exists for the case a transaction *succeeds* and the numbers
 * still do not add up afterwards — which is the only failure mode a
 * transaction cannot protect against, and the one that would otherwise cost a
 * shop its ledger silently.
 *
 * @param {object} file     a file that already passed `validateBackupFile`
 * @param {number} version  its `formatVersion`
 * @returns {Promise<{ok:true, summary:object}>}  rejects with an Arabic message on failure
 */
export async function importBackupFile(file, version) {
  const db = await openDB();

  const target = Array.from(db.objectStoreNames);
  const plan = planRestore(file, version, target);

  // 1 — capture what the device holds right now, before anything is touched.
  const before = await buildBackupFile();
  await saveSafetySnapshot(before);

  const beforeStorage = await readStoreStorage();

  // 2 — write. localStorage first, because it is small, reversible here, and
  //     outside the transaction that matters; IndexedDB second, atomically.
  const applyStorage = (map) => {
    const s = storageBackend();
    if (!s) return;
    const reserved = [];
    for (const k of Object.keys(s)) if (isReservedStorageKey(k)) reserved.push(k);
    if (plan.complete) {
      for (const k of Object.keys(s)) if (!isReservedStorageKey(k)) s.removeItem(k);
    }
    for (const [k, v] of Object.entries(map || {})) s.setItem(k, v);
    return reserved;
  };

  try {
    if (plan.storage) applyStorage(plan.storage);
    await atomicReplace(db, plan);
  } catch (e) {
    // IndexedDB undid itself; localStorage did not.
    try {
      const s = storageBackend();
      if (s && plan.storage) {
        for (const k of Object.keys(s)) if (!isReservedStorageKey(k)) s.removeItem(k);
        for (const [k, v] of Object.entries(beforeStorage || {})) s.setItem(k, v);
      }
    } catch { /* restoring storage is best-effort after an already-failed restore */ }
    throw new Error(e?.message || 'تعذّر الاستيراد');
  }

  // 3 — re-read what actually landed and compare it with the promise.
  const mismatches = await compareToPlan(plan, file);
  if (mismatches.length) {
    try {
      await atomicReplace(db, planRestore(before, before.formatVersion, target));
      const s = storageBackend();
      if (s) {
        for (const k of Object.keys(s)) if (!isReservedStorageKey(k)) s.removeItem(k);
        for (const [k, v] of Object.entries(beforeStorage || {})) s.setItem(k, v);
      }
    } catch (e) {
      throw new Error(
        `التحقق بعد الاستيراد فشل (${mismatches.join('، ')})، وتعذّر التراجع تلقائياً — النسخة التلقائية محفوظة في الشاشة التالية.`,
      );
    }
    throw new Error(
      `التحقق بعد الاستيراد فشل (${mismatches.join('، ')}) — تم التراجع إلى بياناتك السابقة كما كانت.`,
    );
  }

  const live = await readAllStores();
  return {
    ok: true,
    summary: {
      exportedAt: file.exportedAt || null,
      formatVersion: version,
      counts: Object.fromEntries(Object.keys(live).map((n) => [n, live[n].length])),
      totals: computeTotals(live),
      snapshotAt: before.exportedAt,
    },
  };
}
