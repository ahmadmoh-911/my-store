/** The version this build writes. Bump it ONLY per the contract above. */
export const FORMAT_VERSION = 2;

/** Marker that says "this is the file family handled by this module". */
export const FORMAT_KIND = 'storehub-file-backup';

/** Every version this build can read. Never shrink this list. */
export const SUPPORTED_FORMAT_VERSIONS = [1, 2];

/** The legacy `db.exportAll()` marker. */
export const LEGACY_APP_MARK = 'saher';

/**
 * localStorage keys this app reserves for itself. They are NOT shop data, so
 * they are excluded from every file in both directions — in particular the
 * interim activation record, which must never travel in a backup or a restore
 * would re-lock a device with somebody else's gate.
 */
export const RESERVED_STORAGE_PREFIXES = ['saher.interim.', 'saher.backup.'];

/** The identity database: licence, Google session, device and Drive metadata. */
const FORBIDDEN_DATABASES = ['storehub_identity'];

