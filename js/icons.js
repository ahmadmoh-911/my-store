  const d = P[name];
  if (!d) {
    console.warn('[icons] unknown icon:', name);
    return '';
  }
  const s = size || 20; // a viewBox-only <svg> has no intrinsic size, so it
                        // falls back to the 300x150 replaced-element default and
                        // stretches across its flex row, widening the page
